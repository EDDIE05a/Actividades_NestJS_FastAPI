package org.example.model;

public class Product {

    // Se crean los atributos que va a tener la clase

    private int id;
    private String name;
    private String description;
    private double price;
    private int quantity;

    // Constructor para crear objetos a partir de una clase de manera rapida

    public Product(int id, String name, String description, double price, int quantity) {
        this.id = id;
        this.name = name;
        this.description = description;
        this.price = price;
        this.quantity = quantity;
    }

    // Se crean los getters para acceder facilmente los atributos de la clase

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }

    public double getPrice() {
        return price;
    }

    public int getQuantity() {
        return quantity;
    }

    // Se crean setters para poder modificar los atributos de la clase


    public void setId(int id) {
        this.id = id;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public void setPrice(double price) {
        this.price = price;
    }

    public void setQuantity(int quantity) {
        this.quantity = quantity;
    }
}
